pub(super) fn raw(name: &str) -> Option<i32> {
    [
        ("SystemV/AST4ADT", -4 * 3600),
        ("SystemV/CST6CDT", -6 * 3600),
        ("SystemV/EST5EDT", -5 * 3600),
        ("SystemV/MST7MDT", -7 * 3600),
        ("SystemV/PST8PDT", -8 * 3600),
        ("SystemV/YST9YDT", -9 * 3600),
    ]
    .into_iter()
    .find_map(|(zone, raw)| zone.eq_ignore_ascii_case(name).then_some(raw))
}

fn last_sunday(year: i32, month: u32) -> i64 {
    let last = NaiveDate::from_ymd_opt(year, month + 1, 1)
        .unwrap()
        .pred_opt()
        .unwrap();
    (last.and_hms_opt(2, 0, 0).unwrap().and_utc().timestamp()
        - i64::from(last.weekday().num_days_from_sunday()) * 86_400)
        * 1000
}

pub(super) fn offset(ms: i64, raw: i32) -> i64 {
    let raw = i64::from(raw);
    let standard = ms + raw * 1000;
    let year = DateTime::from_timestamp_millis(standard)
        .expect("timeline instants lie within the supported calendar range")
        .year();
    let daylight = if year < 1977 {
        // A conversion is effective at its instant, including negative epochs.
        TRANSITIONS.partition_point(|seconds| seconds * 1000 <= standard) % 2 == 1
    } else {
        // ICU's April rule uses standard time; October uses daylight time.
        let start = last_sunday(year, 4) - raw * 1000;
        let end = last_sunday(year, 10) - (raw + 3600) * 1000;
        ms >= start && ms < end
    };
    raw + if daylight { 3600 } else { 0 }
}
